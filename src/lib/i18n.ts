export const MESSAGES: Record<Lang, Messages> = { ko, en, zh, ja };

/** "{name}" 자리표시자 치환 */
export function fmt(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** 등수 표기: 1등 / 1st / 一等奖 / 1等 */
export function rankLabel(lang: Lang, rank: number) {
  if (lang === "en") return ["", "1st", "2nd", "3rd"][rank] ?? `${rank}th`;
  if (lang === "zh") return ["", "一等奖", "二等奖", "三等奖"][rank] ?? `${rank}等奖`;
  return `${rank}等`.replace("等", lang === "ko" ? "등" : "等");
}
