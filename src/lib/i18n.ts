/**
 * 방문객 화면(등록·완료·당첨 확인) 다국어 문구. ko / en / zh(간체) / ja.
 * 문구를 바꾸면 네 언어를 같이 고친다. 동의 문구를 바꾸면 config.ts 의 CONSENT_VERSION 도 올린다.
 * 법적 효력은 한국어 문구 기준.
 */
export const LANGS = ["ko", "en", "zh", "ja"] as const;
export type Lang = (typeof LANGS)[number];
export const LANG_LABEL: Record<Lang, string> = { ko: "한국어", en: "English", zh: "中文", ja: "日本語" };
/** Intl 포맷용 로케일 */
export const LOCALE: Record<Lang, string> = { ko: "ko-KR", en: "en-US", zh: "zh-CN", ja: "ja-JP" };

export function isLang(v: unknown): v is Lang {
  return typeof v === "string" && (LANGS as readonly string[]).includes(v);
}

/** 브라우저 언어 → 지원 언어 (zh-TW 등도 zh, 그 외는 en) */
export function pickLang(candidates: readonly string[]): Lang {
  for (const c of candidates) {
    const base = c.toLowerCase().split("-")[0];
    if (isLang(base)) return base;
  }
  return "en";
}

